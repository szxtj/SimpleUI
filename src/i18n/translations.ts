export type TranslationKeys = keyof typeof translations.zh;

export function formatArticleCount(count: number, lang: Language = 'zh'): string {
  if (!count || count <= 0) return '';
  if (lang === 'zh') {
    if (count >= 10000) {
      const w = parseFloat((count / 10000).toFixed(0));
      return `${w}万词条`;
    }
    return `${count}词条`;
  } else {
    if (count >= 1000000) {
      const m = parseFloat((count / 1000000).toFixed(2));
      return `${m}M articles`;
    }
    if (count >= 1000) {
      const k = Math.round(count / 1000);
      return `${k}K articles`;
    }
    return `${count} ${count === 1 ? 'article' : 'articles'}`;
  }
}
